export function getRandomQuestions(gameType: string, count: number = 10) {
  let pool: Array<{ id: number; name: string; hint: string; image: string; [key: string]: unknown }> = []
  
  if (gameType === 'car_logo') pool = CAR_LOGOS as any
  else if (gameType === 'brand_logo' || gameType === 'logo_guess') pool = BRAND_LOGOS as any
  else if (gameType === 'phone_guess') pool = PHONE_LOGOS as any
  
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, Math.min(count, shuffled.length))
}

export function generateRoomCode(): string {
  const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'
  let code = ''
  for (let i = 0; i < 6; i++) {
    code += chars[Math.floor(Math.random() * chars.length)]
  }
  return code
}
